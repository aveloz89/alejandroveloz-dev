function applyLanguage(next) {
  lang = next;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (copy[lang][key]) el.textContent = copy[lang][key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    el.setAttribute("aria-label", copy[lang][el.dataset.i18nAria]);
  });
  document.querySelector('meta[name="description"]').content = copy[lang]["meta.description"];
  document.querySelector('meta[property="og:description"]').content = copy[lang]["meta.description"];
  toggle.setAttribute("aria-label", lang === "en" ? "Cambiar a español" : "Switch to English");
  if (caseModal.open && activeCase) renderCase(activeCase);
  toggle.textContent = lang === "en" ? "ES" : "EN";
  document.title = lang === "en" ? "Alejandro Veloz — Senior Software Engineer" : "Alejandro Veloz — Senior Software Engineer | Monterrey";
  localStorage.setItem("av-lang", lang);
}
